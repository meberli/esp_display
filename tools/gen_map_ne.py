#!/usr/bin/env python3
"""Build-time generator for main/map_ne_data.inc (Regen radar background map).

Source: Natural Earth 1:10m vector data (public domain, naturalearthdata.com),
GeoJSON from github.com/nvkelso/natural-earth-vector:
  ne_10m_admin_0_boundary_lines_land, ne_10m_lakes,
  ne_10m_rivers_lake_centerlines, ne_10m_rivers_europe,
  ne_10m_populated_places_simple (+ Buchs SG added by hand).
Usage: python3 tools/gen_map_ne.py <dir with the geojson files>
Points are Web-Mercator zoom-7 world pixels * 4 (quarter-pixel), relative to
the bbox origin, simplified (Douglas-Peucker, 0.5 px) and clipped to the bbox.
"""
import json, math, os, sys

LAT0, LAT1, LON0, LON1 = 45.3, 49.0, 6.3, 12.7
SUB = 4  # quarter pixels
Z = 7

def wx(lon): return (lon + 180.0) / 360.0 * 256 * (1 << Z)
def wy(lat):
    s = math.sin(math.radians(lat))
    return (0.5 - math.log((1 + s) / (1 - s)) / (4 * math.pi)) * 256 * (1 << Z)
OX, OY = wx(LON0), wy(LAT1)
def P(lon, lat): return (round((wx(lon) - OX) * SUB), round((wy(lat) - OY) * SUB))
W, H = P(LON1, LAT0)

def inb(lon, lat): return LON0 <= lon <= LON1 and LAT0 <= lat <= LAT1

def dp(pts, eps):
    if len(pts) < 3: return pts
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    dx, dy = x1 - x0, y1 - y0; L = math.hypot(dx, dy) or 1e-9
    best, bi = -1, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * (pts[i][0] - x0) - dx * (pts[i][1] - y0)) / L if L > 1e-6 else math.hypot(pts[i][0]-x0, pts[i][1]-y0)
        if d > best: best, bi = d, i
    if best <= eps: return [pts[0], pts[-1]]
    return dp(pts[:bi + 1], eps)[:-1] + dp(pts[bi:], eps)

def runs(coords):
    """Split a line into in-bbox runs (keeping one point beyond each edge)."""
    out, cur = [], []
    for i, (lon, lat) in enumerate(coords):
        if inb(lon, lat):
            if not cur and i > 0: cur.append(coords[i - 1])
            cur.append((lon, lat))
        elif cur:
            cur.append((lon, lat)); out.append(cur); cur = []
    if cur: out.append(cur)
    return out

def lines(geom):
    t, c = geom['type'], geom['coordinates']
    if t == 'LineString': return [c]
    if t == 'MultiLineString': return c
    if t == 'Polygon': return c
    if t == 'MultiPolygon': return [r for p in c for r in p]
    return []

def cstr(t):
    r = ''.join(c if c.isascii() else ''.join(f'\\x{b:02X}" "' for b in c.encode()) for c in t)
    return '"' + r + '"'

def load(d, name): return json.load(open(os.path.join(d, name + '.geojson')))['features']

def main(d):
    polys = []  # (kind, [(x,y)])
    def add(kind, feats, keep=lambda p: True):
        for f in feats:
            if f['geometry'] is None or not keep(f['properties']): continue
            for ln in lines(f['geometry']):
                for r in runs([tuple(p[:2]) for p in ln]):
                    pts = dp([P(*q) for q in r], 0.5 * SUB)
                    ded = [pts[0]] + [p for a, p in zip(pts, pts[1:]) if p != a]
                    if len(ded) >= 2: polys.append((kind, ded))
    add(0, load(d, 'ne_10m_admin_0_boundary_lines_land'))
    add(1, load(d, 'ne_10m_lakes'), lambda p: (p.get('scalerank') or 0) <= 10)
    add(2, load(d, 'ne_10m_rivers_lake_centerlines'), lambda p: p.get('featurecla') != 'Lake Centerline')
    add(2, load(d, 'ne_10m_rivers_europe'))
    towns = [(p['properties'].get('pop_max') or 0, p['properties']['name'], *p['geometry']['coordinates'][:2])
             for p in load(d, 'ne_10m_populated_places_simple') if inb(*p['geometry']['coordinates'][:2])]
    towns.append((10**9, 'Buchs SG', 9.478, 47.168))
    towns = [t[1:] for t in sorted(towns, key=lambda t: -t[0])]  # biggest first: label priority
    pts = [p for _, ps in polys for p in ps]
    o = ['// Generated by tools/gen_map_ne.py - do not edit.',
         '// Map data: Natural Earth (public domain), naturalearthdata.com.',
         f'// bbox lat {LAT0}..{LAT1}, lon {LON0}..{LON1}; zoom-7 world px * {SUB} relative to origin.',
         f'#define MAP_NE_ORIGIN_X {OX:.3f}', f'#define MAP_NE_ORIGIN_Y {OY:.3f}', f'#define MAP_NE_SUB {SUB}',
         f'static const int16_t kMapPts[{len(pts)}][2] = {{']
    for i in range(0, len(pts), 8):
        o.append('  ' + ' '.join(f'{{{x},{y}}},' for x, y in pts[i:i + 8]))
    o.append('};')
    o.append(f'static const MapLine kMapLines[{len(polys)}] = {{')
    s = 0
    for k, ps in polys:
        o.append(f'  {{{s}, {len(ps)}, {k}}},'); s += len(ps)
    o.append('};')
    o.append(f'static const MapTown kMapTowns[{len(towns)}] = {{')
    for n, lon, lat in towns:
        x, y = P(lon, lat)
        n = n.replace('Saint Gallen', 'St. Gallen')
        o.append(f'  {{{cstr(n)}, {x}, {y}}},')
    o.append('};')
    out = os.path.join(os.path.dirname(__file__), '..', 'main', 'map_ne_data.inc')
    open(out, 'w').write('\n'.join(o) + '\n')
    print(f'{len(polys)} lines, {len(pts)} points, {len(towns)} towns, ~{len(pts)*4/1024:.1f} KB')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '.')
